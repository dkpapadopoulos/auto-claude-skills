#!/usr/bin/env python3
"""Build the read-only execution-list screen from a frozen report envelope.

    uv run python scripts/build_execution_list.py

Reads ``tests/fixtures/design_seed_pilot/review_report_envelope.json`` and writes ONE
self-contained file to ``artifacts/execution-list.html``. The envelope is the only data
source: nothing here opens ``data/``, a database, or the network, and the generated page
has no remote stylesheet, font or script.

The envelope is embedded VERBATIM in exactly one
``<script type="application/json" id="dion-report">`` element and the page renders itself
from that element at open time (``scripts/execution_list.js``). Nothing is templated into
the markup from the data, so what the reader sees can only have come from the embedded
bytes.

Styles live in ``scripts/execution_list.css`` and ``design/tokens.css`` as real ``.css``
files, inlined here at build time, so ``design/checks/token-lint.sh`` can still scan them
-- the lint reads ``*.css`` and never sees an inline ``<style>`` block.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent

DEFAULT_ENVELOPE = (
    REPO_ROOT / "tests" / "fixtures" / "design_seed_pilot" / "review_report_envelope.json"
)
DEFAULT_OUTPUT = REPO_ROOT / "artifacts" / "execution-list.html"

TOKENS_CSS = REPO_ROOT / "design" / "tokens.css"
SCREEN_CSS = Path(__file__).resolve().parent / "execution_list.css"
SCREEN_JS = Path(__file__).resolve().parent / "execution_list.js"

#: An embedded payload that contains any of these ends the host element early and the
#: rest of it becomes markup. Escaping would silently break "verbatim", so this fails
#: closed instead and says what to do.
_UNSAFE_IN_SCRIPT = ("</script", "<!--", "<![CDATA[")

#: The page must open from disk with no network access of any kind.
_FORBIDDEN_IN_OUTPUT = ("http://", "https://", "//fonts.", "<link", "fetch(", "XMLHttpRequest")


class EnvelopeNotEmbeddable(ValueError):
    """The envelope cannot be embedded verbatim without changing its bytes."""


def _guard_script_payload(text: str, what: str) -> None:
    lowered = text.lower()
    for token in _UNSAFE_IN_SCRIPT:
        if token in lowered:
            raise EnvelopeNotEmbeddable(
                f"{what} contains {token!r}, which would terminate the host <script> "
                f"element. Verbatim embedding is a hard requirement of this screen, so "
                f"this is not escaped away: fix the source, or change the transport."
            )


def render(envelope_text: str) -> str:
    """Return the complete HTML document for ``envelope_text``.

    ``envelope_text`` is embedded byte-for-byte. It is parsed only to fail early on a
    payload that is not JSON at all -- the parsed object is deliberately never used to
    build the markup.
    """
    json.loads(envelope_text)  # fail closed on a non-JSON payload; result unused by design
    _guard_script_payload(envelope_text, "the envelope")

    screen_js = SCREEN_JS.read_text(encoding="utf-8")
    _guard_script_payload(screen_js, "execution_list.js")

    style = TOKENS_CSS.read_text(encoding="utf-8") + "\n" + SCREEN_CSS.read_text(encoding="utf-8")

    return f"""<!doctype html>
<html lang="en" data-theme="light">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Dion — execution list</title>
<!-- Generated by scripts/build_execution_list.py. Read-only, dependency-free, and
     openable straight from disk: no remote stylesheet, font, script or fetch. The
     report envelope below is embedded verbatim and is the only data on this page. -->
<style>
{style}</style>
</head>
<body>

<header class="page">
  <h1>Execution list</h1>
  <span class="sub" id="meta"></span>
  <button id="theme" type="button">Toggle light / dark</button>
</header>

<div id="gate"></div>

<section>
  <h2>Proposed orders</h2>
  <div id="orders"></div>
</section>

<section>
  <h2>Context</h2>
  <div class="grid" id="context"></div>
</section>

<section>
  <h2>Action items</h2>
  <div id="actions"></div>
</section>

<section>
  <h2>What this envelope could not tell you</h2>
  <p class="sub">Recorded rather than papered over. Each of these is a field the screen
    wanted and the envelope does not carry; see
    <span class="mono">artifacts/contract-delta.md</span>.</p>
  <div id="gaps"></div>
</section>

<footer>
  Read-only. This page never places an order, and it re-derives nothing the backend
  already computed — a figure the envelope does not supply is shown as
  <span class="missing-inline">—</span>, never as zero.
</footer>

<script type="application/json" id="dion-report">
{envelope_text}
</script>
<script>
{screen_js}</script>
</body>
</html>
"""


def build(envelope_path: Path, output_path: Path) -> Path:
    """Render ``envelope_path`` to ``output_path`` and return the output path."""
    html = render(envelope_path.read_text(encoding="utf-8"))
    for token in _FORBIDDEN_IN_OUTPUT:
        if token in html:
            raise EnvelopeNotEmbeddable(
                f"the generated page contains {token!r}: it would not be self-contained."
            )
    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(html, encoding="utf-8")
    return output_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--envelope", type=Path, default=DEFAULT_ENVELOPE, help="report envelope JSON"
    )
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT, help="HTML file to write")
    args = parser.parse_args(argv)

    written = build(args.envelope, args.output)
    print(f"wrote {written} ({written.stat().st_size} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
